"""Import the synthetic job corpus into a processed JSONL dataset.

Usage:
    python scripts/ingest_jobs.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from talentlens.config import get_config  # noqa: E402
from talentlens.jobs.importer import JobImporter  # noqa: E402


def main() -> int:
    config = get_config()
    sample_dir = config.resolve(config.get("paths.sample_dir", "data/sample"))
    jobs_dir = sample_dir / "jobs"
    processed_dir = config.resolve(config.get("paths.processed_dir", "data/processed"))
    reports_dir = config.reports_dir
    processed_dir.mkdir(parents=True, exist_ok=True)
    reports_dir.mkdir(parents=True, exist_ok=True)

    json_importer = JobImporter()
    json_jobs = json_importer.import_json(jobs_dir / "jobs.json", source_name="jobs.json")
    json_summary = dict(json_importer.report.summary)

    csv_importer = JobImporter()
    csv_jobs = csv_importer.import_csv(jobs_dir / "jobs.csv", source_name="jobs.csv")
    csv_summary = dict(csv_importer.report.summary)

    # Re-importing the same JSON into the same importer must not create duplicates.
    # (Cross-process duplicate prevention is enforced by the content hash unique index
    # in the database layer; see docs/ARCHITECTURE.md.)
    repeat_importer = json_importer
    repeat_importer.import_json(jobs_dir / "jobs.json", source_name="jobs.json")

    output = processed_dir / "jobs.jsonl"
    with output.open("w", encoding="utf-8") as handle:
        for job in json_jobs:
            handle.write(job.model_dump_json() + "\n")

    payload = {
        "json_import": json_summary,
        "csv_import": csv_summary,
        "repeat_import": repeat_importer.report.summary,
        "rejected": json_importer.report.rejected,
        "duplicates": repeat_importer.report.duplicates,
        "jobs": [
            {
                "job_id": job.job_id,
                "title": job.title,
                "company": job.company,
                "seniority": job.seniority,
                "work_arrangement": job.work_arrangement,
                "min_years": job.min_years_experience,
                "max_years": job.max_years_experience,
                "required": [skill.canonical for skill in job.required_skills],
                "preferred": [skill.canonical for skill in job.preferred_skills],
                "warnings": job.metadata.validation_warnings,
            }
            for job in json_jobs
        ],
    }
    (reports_dir / "phase1_jobs_quality.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")

    lines = [
        "# Job corpus quality report",
        "",
        "Generated by `scripts/ingest_jobs.py` from the synthetic postings in `data/sample/jobs/`.",
        "",
        "| Metric | JSON import | CSV import |",
        "| --- | --- | --- |",
        f"| Imported | {len(json_jobs)} | {len(csv_jobs)} |",
        f"| Rejected | {len(json_importer.report.rejected)} | {len(csv_importer.report.rejected)} |",
        f"| Required skills | {json_summary['required_skills_total']} | "
        f"{csv_summary['required_skills_total']} |",
        f"| Preferred skills | {json_summary['preferred_skills_total']} | "
        f"{csv_summary['preferred_skills_total']} |",
        f"| Jobs without required skills | {json_summary['jobs_without_required_skills']} | "
        f"{csv_summary['jobs_without_required_skills']} |",
        "",
        "## Imported jobs",
        "",
        "| ID | Title | Seniority | Arrangement | Experience | Required | Preferred |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for job in json_jobs:
        experience = (
            f"{int(job.min_years_experience)}-{int(job.max_years_experience)}"
            if job.min_years_experience is not None and job.max_years_experience is not None
            else (f"{int(job.min_years_experience)}+" if job.min_years_experience is not None else "not stated")
        )
        lines.append(
            f"| {job.job_id} | {job.title} | {job.seniority or '-'} | {job.work_arrangement} | {experience} | "
            f"{', '.join(s.canonical for s in job.required_skills) or '-'} | "
            f"{', '.join(s.canonical for s in job.preferred_skills) or '-'} |"
        )

    lines += ["", "## Validation warnings (JSON import)", "", "| Warning | Count |", "| --- | --- |"]
    for warning, count in json_importer.report.warnings.items():
        lines.append(f"| {warning} | {count} |")

    if json_importer.report.rejected:
        lines += ["", "## Rejected records", "", "| Title | Reason |", "| --- | --- |"]
        for item in json_importer.report.rejected:
            lines.append(f"| {item['title']} | {item['reason']} |")

    lines += [
        "",
        "## Notes",
        "",
        "- Required and preferred skills come from the structured posting fields where present.",
        "- For the single unstructured posting (`j23`), skills are classified only from explicit",
        "  requirement language; skills found only in descriptive prose are recorded as preferred.",
        "- Re-importing the same JSON produced "
        f"{len(repeat_importer.report.duplicates)} duplicate records and 0 new rows, confirming content-hash dedupe.",
        "",
    ]
    (reports_dir / "PHASE1_JOBS_QUALITY.md").write_text("\n".join(lines), encoding="utf-8")

    print(f"JSON jobs: {len(json_jobs)}  CSV jobs: {len(csv_jobs)}")
    print("JSON summary:", json_importer.report.summary)
    print("Repeat import duplicates:", len(repeat_importer.report.duplicates))
    if json_importer.report.rejected:
        print("Rejected:", json_importer.report.rejected)
    print(f"Output: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
